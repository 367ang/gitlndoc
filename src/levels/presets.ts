/**
 * 关卡初始化时写入的模板文件内容（development-refinement.md §3 `levels/presets.ts`）。
 *
 * 用途：第一章「创世纪元」是「修复损坏的时间线」，预置文件承担叙事铺垫 ——
 * 玩家进入关卡时，工作区里躺着若干「时间线残片」，接着用真实 git 命令把它们归档。
 *
 * ⚠️ 两条硬约束：
 *   1. **保持精简**（§14：LightningFS 大仓库有性能问题）。每个文件都是几句话，
 *      不做长篇设定文案 —— 这些内容会真实写入 `/repo` 并被 git 追踪。
 *   2. 内容与路径**用中文**，路径保持英文（`README.md` / `notes/*.md`），
 *      与仓库既有笔记风格一致。
 *
 * ⚠️ 关于「文档换行」：LightningFS 与 git 按字节存取，换行符会进入 blob。
 * 本文件统一用 `\n`，`targetState` 的 `file` 比对也会做 CRLF 归一，
 * 因此玩家在任意平台编辑后内容匹配都不会因行尾差异误判。
 */

